"""Windows EXE version metadata for the GC Agent frozen executable.

The single version source is ``github_community_agent.__version__`` (kept equal
to pyproject.toml by tests). This module derives from it:

* the PyInstaller ``--version-file`` (VSVersionInfo) for GitHubCommunityAgent.exe;
* the Inno Setup ``AppVersion`` spelling (``1.0.0rc1`` -> ``1.0.0-rc1``).

Windows numeric file versions cannot express pre-releases, so ``1.0.0rc1`` and
``1.0.0`` both get FileVersion 1.0.0.0; the string FileVersion/ProductVersion
carry the exact PEP 440 version. Subcommands:

  write   --output NEW.txt         create-only version file
  inno                              print the Inno Setup spelling
  check   --exe GitHubCommunityAgent.exe   compare EXE resources with __version__
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
_PEP440 = re.compile(r"^(\d+)\.(\d+)\.(\d+)(?:(\.dev|rc|a|b)(\d+))?$")

COMPANY = "NATURE AI CORP"
PRODUCT = "GitHub Community Agent"
DESCRIPTION = "GitHub Community Agent (independent; not affiliated with GitHub, Inc.)"
COPYRIGHT = "Copyright 2026 NATURE AI CORP and contributors. Apache License 2.0."


def package_version() -> str:
    text = (ROOT / "src" / "github_community_agent" / "__init__.py").read_text(encoding="utf-8")
    return re.search(r'^__version__ = "([^"]+)"', text, re.M).group(1)


def numeric(version: str) -> tuple[int, int, int, int]:
    m = _PEP440.match(version)
    if not m:
        raise ValueError(f"Unsupported version for Windows metadata: {version!r}")
    return int(m.group(1)), int(m.group(2)), int(m.group(3)), 0


def inno(version: str) -> str:
    numeric(version)
    return re.sub(r"\.?(dev|rc|a|b)(\d+)$", r"-\1\2", version)


def render(version: str) -> str:
    nums = numeric(version)
    strings = [
        ("CompanyName", COMPANY),
        ("FileDescription", DESCRIPTION),
        ("FileVersion", version),
        ("InternalName", "GitHubCommunityAgent"),
        ("LegalCopyright", COPYRIGHT),
        ("OriginalFilename", "GitHubCommunityAgent.exe"),
        ("ProductName", PRODUCT),
        ("ProductVersion", version),
    ]
    body = ",\n".join(f"          StringStruct({k!r}, {v!r})" for k, v in strings)
    return f"""# UTF-8
# Generated by scripts/windows_version_info.py from github_community_agent.__version__.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={nums},
    prodvers={nums},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [
{body}
        ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def read_exe(exe: Path) -> dict[str, str]:
    import pefile
    pe = pefile.PE(str(exe), fast_load=True)
    pe.parse_data_directories([pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_RESOURCE"]])
    out: dict[str, str] = {}
    for info in getattr(pe, "FileInfo", None) or []:
        for entry in info:
            for table in getattr(entry, "StringTable", []):
                out.update({k.decode(): v.decode() for k, v in table.entries.items()})
    if getattr(pe, "VS_FIXEDFILEINFO", None):
        f = pe.VS_FIXEDFILEINFO[0]
        out["_numeric"] = "%d.%d.%d.%d" % (f.FileVersionMS >> 16, f.FileVersionMS & 0xFFFF,
                                            f.FileVersionLS >> 16, f.FileVersionLS & 0xFFFF)
    return out


def check_exe(exe: Path, version: str) -> list[str]:
    got = read_exe(exe)
    errors = []
    for key in ("FileVersion", "ProductVersion"):
        if got.get(key) != version:
            errors.append(f"EXE {key} {got.get(key)!r} != package version {version!r}")
    if got.get("_numeric") != "%d.%d.%d.%d" % numeric(version):
        errors.append(f"EXE numeric version {got.get('_numeric')!r} != {numeric(version)}")
    if got.get("ProductName") != PRODUCT or got.get("CompanyName") != COMPANY:
        errors.append("EXE ProductName/CompanyName missing or wrong")
    return errors


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    w = sub.add_parser("write")
    w.add_argument("--output", type=Path, required=True)
    sub.add_parser("inno")
    c = sub.add_parser("check")
    c.add_argument("--exe", type=Path, required=True)
    args = p.parse_args(argv)
    version = package_version()
    if args.cmd == "write":
        with args.output.open("x", encoding="utf-8") as fh:
            fh.write(render(version))
        print(f"Version file for {version} written: {args.output}")
        return 0
    if args.cmd == "inno":
        print(inno(version))
        return 0
    errors = check_exe(args.exe, version)
    for e in errors:
        print("FAIL:", e)
    print("EXE VERSION METADATA MATCHES" if not errors else "EXE VERSION METADATA MISMATCH", version)
    return 0 if not errors else 1


if __name__ == "__main__":
    sys.exit(main())
